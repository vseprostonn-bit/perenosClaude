# Вес каждого атрибута в итоговом совпадении. Тип вещи решает больше всего:
# тренч против пальто - разные вещи, даже если всё остальное совпало.
ATTRIBUTE_WEIGHTS: dict[str, float] = {
    "type": 0.34,
    "silhouette": 0.16,
    "length": 0.16,
    "sleeve": 0.12,
    "fit": 0.10,
    "neckline": 0.06,
    "pattern": 0.06,
}


@dataclass
class Attributes:
    """Паспорт вещи. None означает «не определено», а не «отсутствует»."""

    type: str | None = None
    silhouette: str | None = None
    length: str | None = None
    sleeve: str | None = None
    neckline: str | None = None
    fit: str | None = None
    pattern: str | None = None
    details: list[str] = field(default_factory=list)

    def known(self) -> dict[str, str]:
        return {k: v for k, v in self.__dict__.items()
                if k != "details" and isinstance(v, str) and v}


def _match_dict(text: str, table: dict[str, tuple[str, ...]]) -> str | None:
    for value, keys in table.items():
        if any(k in text for k in keys):
            return value
    return None


def parse_title(title: str) -> Attributes:
    """Достаёт атрибуты из названия каталожной вещи.

    Названия в фидах короткие («Тренч оверсайз двубортный»), поэтому заполнится
    два-три поля - этого достаточно, пустые поля просто не участвуют в сравнении.
    """
    low = re.sub(r"\s+", " ", title.lower())
    return Attributes(
        type=_match_dict(low, TYPES),
        silhouette=_match_dict(low, SILHOUETTES),
        length=_match_dict(low, LENGTHS),
        sleeve=_match_dict(low, SLEEVES),
        neckline=_match_dict(low, NECKLINES),
        fit=_match_dict(low, FITS),
        pattern=_match_dict(low, PATTERNS),
    )


def color_score(want: str | None, have: str | None) -> float:
    """1.0 - тот же цвет, 0.6 - соседний оттенок, 0.0 - другой."""
    if not want or not have:
        return 0.0
    if want == have:
        return 1.0
    return 0.6 if have in COLOR_NEIGHBOURS.get(want, ()) else 0.0


def attribute_score(want: Attributes, have: Attributes) -> float:
    """Совпадение паспортов от 0 до 1.

    Считаем только по полям, известным у ОБЕИХ вещей: если у каталожной вещи в
    названии нет длины, это не её вина и не повод штрафовать. Так короткие
    названия из фида не проигрывают подробным.
    """
    total = matched = 0.0
    for field_name, weight in ATTRIBUTE_WEIGHTS.items():
        a, b = getattr(want, field_name), getattr(have, field_name)
        if not a or not b:
            continue
        total += weight
        if a == b:
            matched += weight
    if total == 0:
        return 0.0
    return matched / total


def allowed_values() -> dict[str, list[str]]:
    """Значения для промпта разбора: модель обязана выбирать только отсюда."""
    values = {name: list(table.keys()) for name, table in ATTRIBUTE_DICTS.items()}
    values["color"] = list(COLOR_NEIGHBOURS.keys())
    return values
