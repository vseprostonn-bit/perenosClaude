# Тип вещи -> слот образа. Нужен как вето при матчинге: категория в каталоге
# приходит из фида и местами врёт, поэтому под слот «верх» может попасть обувь.
# Тип из названия надёжнее категории продавца - по нему и отсекаем.
SLOT_BY_TYPE: dict[str, str] = {
    **{t: "top" for t in ("рубашка", "блузка", "футболка", "поло", "топ",
                          "водолазка", "свитер")},
    **{t: "bottom" for t in ("джинсы", "брюки", "юбка", "шорты", "легинсы")},
    **{t: "dress" for t in ("платье", "сарафан", "комбинезон", "костюм")},
    **{t: "outerwear" for t in ("тренч", "пальто", "куртка", "пуховик", "плащ",
                                "пиджак", "кардиган", "жилет", "шуба")},
    **{t: "shoes" for t in ("кроссовки", "ботинки", "сапоги", "туфли", "лоферы",
                            "босоножки", "балетки")},
    **{t: "bag" for t in ("сумка", "рюкзак", "клатч")},
}


def slot_of(passport: Attributes) -> str | None:
    """Слот по типу вещи. None - тип не распознан, вето не накладываем."""
    return SLOT_BY_TYPE.get(passport.type or "")


def slots_conflict(want_slot: str, passport: Attributes) -> bool:
    """Правда ли, что вещь заведомо не из нужного слота.

    Аксессуары не проверяем: там типы не описаны, и вето отсекло бы всё.
    """
    if want_slot == "accessory":
        return False
    found = slot_of(passport)
    return found is not None and found != want_slot


