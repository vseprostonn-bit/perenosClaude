"""Вырезание вещи из фото лука под конкретный слот.

Причина №1 промахов визуального матчинга (методология Саши, 03.09.2026,
docs/metodologiya-matchinga-2026-09-03.md): эмбеддинг всего кадра - это «девушка,
поза, фон», а карточка каталога - «вещь на белом». Их близость говорит о фоне, а
не о вещи. Пока вещь не вырезана, визуального матчинга нет.

v1 - грубый эвристический кроп по вертикальным полосам для съёмки в рост: верх
берём из верхней половины кадра, брюки из нижней, обувь у пола. Это «костыль на
старте» из методологии (этап Э2, вариант 3): работает мгновенно, без тяжёлых
весов, и уже лучше целого кадра. Детектор одежды (YOLOv8-seg / DeepFashion2) -
следующий шаг за тем же интерфейсом `crop_for`, когда линейка покажет потолок
эвристики.

Интерфейс намеренно один: `crop_for(image, category) -> bytes | None`. None значит
«надёжно вырезать не смогли» - вызывающий код тогда НЕ подставляет весь кадр
(фон увёл бы матч), а просто работает по этой вещи без визуального сигнала.
"""

from __future__ import annotations

import io
import logging

log = logging.getLogger(__name__)

# Вертикальные полосы (доли высоты кадра) для съёмки человека в полный рост.
# Ширину не режем: где в кадре стоит человек - неизвестно, обрезка вбок рискует
# отхватить саму вещь. Полосы намеренно с запасом и перекрытием.
# Сумки и аксессуары не режем: их положение в кадре непредсказуемо (в руке, на
# плече, на сгибе локтя) - неверный кроп хуже, чем матчинг по цвету и типу.
_BANDS: dict[str, tuple[float, float]] = {
    "top": (0.08, 0.56),
    "outerwear": (0.05, 0.66),
    "dress": (0.10, 0.85),
    "bottom": (0.45, 0.98),
    "shoes": (0.82, 1.00),
}

_MIN_BAND_PX = 24  # уже вырожденный кроп смысла не несёт - лучше текст-онли


def crop_for(image: bytes, category: str) -> bytes | None:
    """JPEG-кроп вещи под слот или None, если надёжно вырезать нельзя.

    None - для слотов без полосы (bag, accessory), для битого изображения и для
    слишком мелкого кадра, где полоса вырождается в пиксели.
    """
    band = _BANDS.get(category)
    if band is None:
        return None
    try:
        from PIL import Image

        img = Image.open(io.BytesIO(image)).convert("RGB")
        width, height = img.size
        top = int(height * band[0])
        bottom = int(height * band[1])
        if bottom - top < _MIN_BAND_PX or width < _MIN_BAND_PX:
            return None
        crop = img.crop((0, top, width, bottom))
        buf = io.BytesIO()
        crop.save(buf, format="JPEG", quality=90)
        return buf.getvalue()
    except Exception as exc:  # noqa: BLE001 - любой сбой = работаем без визуала
        log.warning("не удалось вырезать вещь (%s): %s", category, exc)
        return None
